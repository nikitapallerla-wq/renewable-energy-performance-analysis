-- =====================================================
-- 1. DATA VALIDATION & EXPLORATION
-- =====================================================


-- Q1: Validate monthly generation record count

SELECT
    COUNT(*) AS total_records
FROM monthly_generation;


-- Q2: Check duplicate plant-month records

SELECT
    plant_id,
    month,
    COUNT(*) AS record_count
FROM monthly_generation
GROUP BY plant_id, month
HAVING COUNT(*) > 1;


-- Q3: Check missing values in monthly generation

SELECT
    COUNT(*) FILTER (WHERE plant_id IS NULL) AS null_plant_id,
    COUNT(*) FILTER (WHERE energy_generated_kwh IS NULL) AS null_generation,
    COUNT(*) FILTER (WHERE energy_exported_kwh IS NULL) AS null_export,
    COUNT(*) FILTER (WHERE import_units IS NULL) AS null_import_units
FROM monthly_generation;


-- Q4: Total energy generated by plant

SELECT
    plant_id,
    SUM(energy_generated_kwh) AS total_energy_generated
FROM monthly_generation
GROUP BY plant_id
ORDER BY total_energy_generated DESC;


-- Q5: Plant with highest total generation

SELECT
    plant_id,
    SUM(energy_generated_kwh) AS total_energy_generated
FROM monthly_generation
GROUP BY plant_id
ORDER BY total_energy_generated DESC
LIMIT 1;


-- Q6: Monthly energy generation

SELECT
    month,
    SUM(energy_generated_kwh) AS total_energy_generated
FROM monthly_generation
GROUP BY month
ORDER BY month;


-- Q7: Month with highest total generation

SELECT
    month,
    SUM(energy_generated_kwh) AS total_energy_generated
FROM monthly_generation
GROUP BY month
ORDER BY total_energy_generated DESC
LIMIT 1;


-- Q8: Generation vs export by plant and month

SELECT
    plant_id,
    month,
    SUM(energy_generated_kwh) AS total_energy_generated,
    SUM(energy_exported_kwh) AS total_energy_exported
FROM monthly_generation
GROUP BY plant_id, month;


-- Q9: Monthly export efficiency

SELECT
    plant_id,
    month,
    SUM(energy_generated_kwh) AS total_energy_generated,
    SUM(energy_exported_kwh) AS total_energy_exported,
    ROUND(
        SUM(energy_exported_kwh) /
        NULLIF(SUM(energy_generated_kwh), 0) * 100,
        2
    ) AS export_efficiency_pct
FROM monthly_generation
GROUP BY plant_id, month;


-- Q10: Plant with highest average export efficiency

SELECT
    plant_id,
    AVG(export_efficiency) AS avg_export_efficiency
FROM (
    SELECT
        plant_id,
        month,
        SUM(energy_exported_kwh) /
        NULLIF(SUM(energy_generated_kwh), 0) * 100
        AS export_efficiency
    FROM monthly_generation
    GROUP BY plant_id, month
) AS monthly_efficiency
GROUP BY plant_id
ORDER BY avg_export_efficiency DESC
LIMIT 1;



-- =====================================================
-- 2. GENERATION & PLANT PERFORMANCE
-- =====================================================


-- Q11: Total energy generation by financial year

SELECT
    financial_year,
    SUM(energy_generated_kwh) AS total_energy_generated
FROM monthly_generation
GROUP BY financial_year
ORDER BY financial_year;


-- Q12: Top-performing plant in each financial year

WITH ranked_plants AS (
    SELECT
        plant_id,
        financial_year,
        SUM(energy_generated_kwh) AS total_energy_generated,
        DENSE_RANK() OVER (
            PARTITION BY financial_year
            ORDER BY SUM(energy_generated_kwh) DESC
        ) AS generation_rank
    FROM monthly_generation
    GROUP BY plant_id, financial_year
)
SELECT
    plant_id,
    financial_year,
    total_energy_generated
FROM ranked_plants
WHERE generation_rank = 1
ORDER BY financial_year;


-- Q13: Classify plants based on total generation

WITH plant_generation AS (
    SELECT
        plant_id,
        SUM(energy_generated_kwh) AS total_energy_generated
    FROM monthly_generation
    GROUP BY plant_id
)
SELECT
    plant_id,
    total_energy_generated,
    CASE
        WHEN total_energy_generated > 5000000 THEN 'High'
        WHEN total_energy_generated >= 2000000 THEN 'Medium'
        ELSE 'Low'
    END AS performance_category
FROM plant_generation
ORDER BY total_energy_generated DESC;


-- Q14: Count plants in each performance category

WITH plant_generation AS (
    SELECT
        plant_id,
        SUM(energy_generated_kwh) AS total_energy_generated
    FROM monthly_generation
    GROUP BY plant_id
),
classified_plants AS (
    SELECT
        plant_id,
        total_energy_generated,
        CASE
            WHEN total_energy_generated > 5000000 THEN 'High'
            WHEN total_energy_generated >= 2000000 THEN 'Medium'
            ELSE 'Low'
        END AS performance_category
    FROM plant_generation
)
SELECT
    performance_category,
    COUNT(*) AS plant_count
FROM classified_plants
GROUP BY performance_category
ORDER BY plant_count DESC;



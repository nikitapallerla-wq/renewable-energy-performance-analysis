-- Q31: Total invoice amount by financial year
-- Financial year is derived because the source financial_year
-- column is NULL in the billing table.

WITH billing_fy AS (
    SELECT
        CASE
            WHEN EXTRACT(
                MONTH FROM TO_DATE('01-' || billing_month, 'DD-Mon-YY')
            ) >= 4
            THEN 'FY ' ||
                 EXTRACT(
                     YEAR FROM TO_DATE('01-' || billing_month, 'DD-Mon-YY')
                 ) ||
                 '-' ||
                 RIGHT(
                     (
                         EXTRACT(
                             YEAR FROM TO_DATE('01-' || billing_month, 'DD-Mon-YY')
                         ) + 1
                     )::text,
                     2
                 )
            ELSE 'FY ' ||
                 (
                     EXTRACT(
                         YEAR FROM TO_DATE('01-' || billing_month, 'DD-Mon-YY')
                     ) - 1
                 ) ||
                 '-' ||
                 RIGHT(
                     EXTRACT(
                         YEAR FROM TO_DATE('01-' || billing_month, 'DD-Mon-YY')
                     )::text,
                     2
                 )
        END AS derived_financial_year,
        invoice_amount
    FROM billing
)
SELECT
    derived_financial_year,
    SUM(invoice_amount) AS total_invoice_amount
FROM billing_fy
GROUP BY derived_financial_year
ORDER BY derived_financial_year;



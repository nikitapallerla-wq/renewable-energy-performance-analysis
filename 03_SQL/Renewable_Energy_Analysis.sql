-- Q50: Combine billing and generation performance by plant

WITH billing_summary AS (
    SELECT
        plant_id,
        SUM(invoice_amount) AS total_invoice_amount,
        SUM(amount_receivable) AS total_amount_receivable
    FROM billing
    GROUP BY plant_id
),
generation_summary AS (
    SELECT
        plant_id,
        SUM(energy_generated_kwh) AS total_energy_generated,
        SUM(energy_exported_kwh) AS total_energy_exported
    FROM monthly_generation
    GROUP BY plant_id
)
SELECT
    b.plant_id,
    b.total_invoice_amount,
    b.total_amount_receivable,
    g.total_energy_generated,
    g.total_energy_exported
FROM billing_summary b
JOIN generation_summary g
    ON b.plant_id = g.plant_id
ORDER BY b.plant_id;



